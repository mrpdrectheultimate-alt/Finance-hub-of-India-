import { createServerClient } from "@supabase/ssr";
import { NextRequest, NextResponse } from "next/server";
import type { Database } from "@/types/database";
import { getRequestOrigin } from "@/lib/url";

export const dynamic = "force-dynamic";

export async function GET(req: NextRequest) {
  const origin = getRequestOrigin(req);

  try {
    const requestUrl = new URL(req.url);
    const next = requestUrl.searchParams.get("next") || "/dashboard";
    const safeNext = next.startsWith("/") && !next.startsWith("//") ? next : "/dashboard";

    const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
    const supabaseAnonKey =
      process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ||
      process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY;

    if (!supabaseUrl || !supabaseAnonKey) {
      return NextResponse.redirect(`${origin}/login?error=missing_supabase_env`);
    }

    const pendingCookies: Array<{ name: string; value: string; options?: any }> = [];

    const supabase = createServerClient<Database>(supabaseUrl, supabaseAnonKey, {
      cookies: {
        get(name: string) {
          return req.cookies.get(name)?.value;
        },
        set(name: string, value: string, options: any) {
          pendingCookies.push({ name, value, options });
        },
        remove(name: string, options: any) {
          pendingCookies.push({ name, value: "", options: { ...options, maxAge: 0 } });
        },
        getAll() {
          return req.cookies.getAll();
        },
        setAll(cookiesToSet: Array<{ name: string; value: string; options?: any }>) {
          cookiesToSet.forEach((c: { name: string; value: string; options?: any }) => pendingCookies.push(c));
        },
      },
    });

    const redirectTo = `${origin}/api/auth/callback?next=${encodeURIComponent(safeNext)}`;
    const { data, error } = await supabase.auth.signInWithOAuth({
      provider: "google",
      options: {
        redirectTo,
        skipBrowserRedirect: true,
        queryParams: {
          access_type: "offline",
          prompt: "consent",
        },
      },
    });

    if (error || !data.url) {
      console.error("Google OAuth error:", error);
      return NextResponse.redirect(
        `${origin}/login?error=${encodeURIComponent(error?.message || "google_oauth_unavailable")}`
      );
    }

    const redirectResponse = NextResponse.redirect(data.url);
    // Copy all cookies generated by signInWithOAuth (including PKCE code verifier)
    pendingCookies.forEach(({ name, value, options }) => {
      redirectResponse.cookies.set(name, value, {
        ...options,
        path: "/",
        sameSite: "lax",
        secure: process.env.NODE_ENV === "production",
      });
    });

    return redirectResponse;
  } catch (err: unknown) {
    console.error("Google Auth API Exception:", err);
    return NextResponse.redirect(`${origin}/login?error=google_oauth_exception`);
  }
}
